-- 9.1 INNER JOIN: filmes com suas respectivas categorias
--     (exclui filmes sem categoria)
SELECT
    f.id          AS filme_id,
    f.titulo,
    f.ano_lancamento,
    f.diretor,
    c.nome        AS categoria
FROM  Filmes      f
INNER JOIN Categorias c ON c.id = f.id_categoria
ORDER BY f.titulo;


-- 9.2 LEFT JOIN: todos os filmes, inclusive sem categoria
SELECT
    f.id          AS filme_id,
    f.titulo,
    f.ano_lancamento,
    f.diretor,
    COALESCE(c.nome, 'Sem Categoria') AS categoria
FROM  Filmes      f
LEFT  JOIN Categorias c ON c.id = f.id_categoria
ORDER BY f.titulo;


-- 10. UNION: lista única de "nomes" do sistema
--     (nomes de categorias + títulos de filmes)
SELECT nome   AS nome_no_sistema, 'Categoria' AS origem
FROM   Categorias

UNION

SELECT titulo AS nome_no_sistema, 'Filme'     AS origem
FROM   Filmes

ORDER BY nome_no_sistema;


-- 11. Quantidade de filmes por categoria (GROUP BY + COUNT)
SELECT
    COALESCE(c.nome, 'Sem Categoria') AS categoria,
    COUNT(f.id)                        AS total_filmes
FROM  Filmes      f
LEFT  JOIN Categorias c ON c.id = f.id_categoria
GROUP BY c.id, c.nome
ORDER BY total_filmes DESC;

